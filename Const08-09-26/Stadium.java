class Stadium {
    String name;
    String location;
    int capacity;
    String sport;
    boolean indoor;

    Stadium() {
    }

    Stadium(String name, String location, int capacity, String sport, boolean indoor) {
        this.name = name;
        this.location = location;
        this.capacity = capacity;
        this.sport = sport;
        this.indoor = indoor;
    }
}
