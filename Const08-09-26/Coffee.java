class Coffee {
    String name;
    String type;
    double price;
    String size;
    boolean hot;

    Coffee() {
    }

    Coffee(String name, String type, double price, String size, boolean hot) {
        this.name = name;
        this.type = type;
        this.price = price;
        this.size = size;
        this.hot = hot;
    }
}
