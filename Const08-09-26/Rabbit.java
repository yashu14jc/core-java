class Rabbit {
    String name;
    String color;
    double weight;
    int age;
    boolean domestic;

    Rabbit() {
    }

    Rabbit(String name, String color, double weight, int age, boolean domestic) {
        this.name = name;
        this.color = color;
        this.weight = weight;
        this.age = age;
        this.domestic = domestic;
    }
}
