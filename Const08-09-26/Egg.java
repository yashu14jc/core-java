class Egg {
    String type;
    String color;
    double price;
    int quantity;
    boolean fresh;

    Egg() {
    }

    Egg(String type, String color, double price, int quantity, boolean fresh) {
        this.type = type;
        this.color = color;
        this.price = price;
        this.quantity = quantity;
        this.fresh = fresh;
    }
}
