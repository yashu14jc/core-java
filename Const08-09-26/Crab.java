class Crab {
    String type;
    double weight;
    double price;
    String color;
    boolean fresh;

    Crab() {
    }

    Crab(String type, double weight, double price, String color, boolean fresh) {
        this.type = type;
        this.weight = weight;
        this.price = price;
        this.color = color;
        this.fresh = fresh;
    }
}
