class Crocodile {
    String name;
    double length;
    double weight;
    String habitat;
    boolean dangerous;

    Crocodile() {
    }

    Crocodile(String name, double length, double weight, String habitat, boolean dangerous) {
        this.name = name;
        this.length = length;
        this.weight = weight;
        this.habitat = habitat;
        this.dangerous = dangerous;
    }
}
