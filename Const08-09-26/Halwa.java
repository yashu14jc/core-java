class Halwa {
    String name;
    String type;
    double price;
    String color;
    boolean sweet;

    Halwa() {
    }

    Halwa(String name, String type, double price, String color, boolean sweet) {
        this.name = name;
        this.type = type;
        this.price = price;
        this.color = color;
        this.sweet = sweet;
    }
}
