class Fish {
    String name;
    double weight;
    double price;
    String waterType;
    boolean fresh;

    Fish() {
    }

    Fish(String name, double weight, double price, String waterType, boolean fresh) {
        this.name = name;
        this.weight = weight;
        this.price = price;
        this.waterType = waterType;
        this.fresh = fresh;
    }
}
