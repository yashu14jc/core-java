class Sunflower {
    String color;
    double height;
    double price;
    String season;
    boolean fresh;

    Sunflower() {
    }

    Sunflower(String color, double height, double price, String season, boolean fresh) {
        this.color = color;
        this.height = height;
        this.price = price;
        this.season = season;
        this.fresh = fresh;
    }
}
