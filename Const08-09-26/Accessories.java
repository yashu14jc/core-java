class Accessories {
    String name;
    String brand;
    double price;
    String material;
    boolean available;

    Accessories() {
    }

    Accessories(String name, String brand, double price, String material, boolean available) {
        this.name = name;
        this.brand = brand;
        this.price = price;
        this.material = material;
        this.available = available;
    }
}
